package com.ledgermate.report;

import java.util.List;

/**
 * Builds RFC 4180 style CSV. Free-text cells that start with a spreadsheet formula character
 * (= + - @ tab CR) are prefixed with an apostrophe so Excel/Sheets show them as text instead of
 * executing them (CSV / formula injection). Numeric columns are written as plain numbers.
 */
public final class CsvExporter {

    public static final String NEWLINE = "\r\n";

    /** One output row. Money fields are plain decimal strings such as "5000.00" / "-1500.00". */
    public record Line(String date, String type, String amount, String signedAmount,
                       String counterparty, String description, String reference,
                       String runningBalance, String entryType, String relatedEntry, String reason) {}

    private CsvExporter() {}

    public static String build(String zoneLabel, List<Line> lines) {
        StringBuilder sb = new StringBuilder();
        sb.append(String.join(",",
                "Date (" + zoneLabel + ")", "Type", "Amount", "Signed Amount", "Counterparty",
                "Description", "Reference", "Running Balance", "Entry Type", "Related Entry", "Reason"));
        sb.append(NEWLINE);
        for (Line l : lines) {
            sb.append(String.join(",",
                    text(l.date()), text(l.type()), number(l.amount()), number(l.signedAmount()),
                    text(l.counterparty()), text(l.description()), text(l.reference()),
                    number(l.runningBalance()), text(l.entryType()), text(l.relatedEntry()),
                    text(l.reason())));
            sb.append(NEWLINE);
        }
        return sb.toString();
    }

    /** Free-text cell: neutralise formulas, then quote if needed. */
    public static String text(String raw) {
        if (raw == null || raw.isEmpty()) {
            return "";
        }
        String value = raw;
        char first = value.charAt(0);
        if (first == '=' || first == '+' || first == '-' || first == '@' || first == '\t' || first == '\r') {
            value = "'" + value;
        }
        return quoteIfNeeded(value);
    }

    /** Numeric cell: written as-is (they are generated by the server, never user text). */
    private static String number(String value) {
        return value == null ? "" : value;
    }

    private static String quoteIfNeeded(String value) {
        if (value.indexOf(',') >= 0 || value.indexOf('"') >= 0
                || value.indexOf('\n') >= 0 || value.indexOf('\r') >= 0) {
            return "\"" + value.replace("\"", "\"\"") + "\"";
        }
        return value;
    }
}
